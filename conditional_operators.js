"use strict";
// Conditional Operators
// Compare two values
let a = 3;
let b = 1;
console.log(a === b);
console.log(a !== b);
// Compare Strings
let value1 = "Srinivas";
let value2 = "Moolya";
console.log(value1 === value2);
console.log(value1 !== value2);
// Others
console.log(a > b);
console.log(a < b);
console.log(a >= b);
console.log(a <= b);
